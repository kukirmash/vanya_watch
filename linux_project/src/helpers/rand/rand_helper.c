#include "helpers/rand/rand_helper.h"

#if ESP32
#include "esp_random.h"
#endif

//-----------------------------------------------------------------------------------------
// Функция-обертка для генерации случайного числа на разных платформах
uint32_t rand_get_random(void)
{
#if ESP32
    return esp_random();
#else
    return rand();
#endif
}

